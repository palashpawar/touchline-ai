"""Regenerate docs/QUALITY_SIGNALS.md from the code (single source of truth)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from touchline import quality  # noqa: E402
from touchline.agent import policy  # noqa: E402
from touchline.vision import motion  # noqa: E402

L = ["# Quality signals", "", "Generated by `scripts/gen_signal_doc.py` from `backend/touchline/quality.py`. Every signal is a measured",
     "quantity with a unit and a threshold chosen by inspecting the development clip and the stress tests. **None of these is a",
     "calibrated probability**; they are heuristic indicators. `n/a` means not measurable for that segment.", "",
     "| Key | Signal | Unit | Breach when | Threshold | Definition | Limitations |", "|---|---|---|---|---|---|---|"]
for s in quality.spec_table():
    L.append(f"| `{s['key']}` | {s['label']} | {s['unit']} | {s['bad_when']} | {s['threshold']} | {s['definition']} | {s['limitations'] or '—'} |")
L += ["", "## Triggers", "", "Breaches of " + ", ".join(f"`{k}`" for k in quality.TRIGGERS) + " drive `PLAN_RECOVERY`. "
      "Camera signals (" + ", ".join(f"`{k}`" for k in policy.CAMERA_SIGNALS) + ") lead to the camera-motion update (if the motion "
      "model validates) or to review; tracking signals (" + ", ".join(f"`{k}`" for k in policy.TRACKING_SIGNALS) + ") lead to denser "
      "sampling. `camera_drift_px` stops counting once a segment runs motion-compensated.",
      "", "## Motion-model validation", "",
      f"Validated when ≥ {motion.MIN_INLIERS} MAGSAC inliers, inlier ratio ≥ {motion.MIN_INLIER_RATIO}, median inlier reprojection "
      f"error ≤ {motion.MAX_REPROJ_PX} px (estimated at {motion.WORK_WIDTH} px width, rescaled), and 0.5 < det(A) < 2 with small perspective terms.",
      "", "## Acceptance rule (compare_runs)", "",
      f"On identical evaluation frames: at least one target signal improves ≥ {int(policy.MIN_REL_IMPROVEMENT * 100)}% (relative); no target "
      f"gets ≥ {int(policy.MIN_REL_IMPROVEMENT * 100)}% worse while ending beyond its threshold; guards: line alignment may not drop > 0.05, "
      "off-pitch share may not rise > 0.05, kept detections per frame may not fall > 20%. Camera-motion updates are judged on "
      "`line_alignment` and `out_of_pitch_fraction`; densify on the breached tracking signals.",
      "", f"Retry budget {policy.MAX_ATTEMPTS} per segment; stride schedule {list(policy.STRIDE_SCHEDULE)}."]
(ROOT / "docs/QUALITY_SIGNALS.md").write_text("\n".join(L) + "\n")
print("wrote docs/QUALITY_SIGNALS.md")
